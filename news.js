// サウニュ〜（サウナニュース）の記事データと純関数。
// 一次情報（施設・主催者の公式発表）に基づく記事だけを置く。
// 本文はブロック配列。描画は renderNewsBlocks を SSR / SPA で共有する。

export const NEWS_CATEGORIES = {
  opening: "新店・開店",
  event: "イベント",
  renewal: "リニューアル",
  closure: "休業・閉店",
  award: "受賞・発表",
};

export function newsCategoryLabel(category) {
  return NEWS_CATEGORIES[category] || "ニュース";
}

export function escapeNewsHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

// 公開対象の記事を公開日の新しい順に返す（同日は slug 昇順）。
export function getPublishedNews(articles, today) {
  const todayText = today || new Date().toISOString().slice(0, 10);
  return articles
    .filter((article) => article.status === "published" && article.publishedAt <= todayText)
    .slice()
    .sort((a, b) => (a.publishedAt === b.publishedAt
      ? a.slug.localeCompare(b.slug)
      : b.publishedAt.localeCompare(a.publishedAt)));
}

// 厚み判定用の本文テキスト量（見出しを除く本文ブロックの文字数）。
export function newsBodyTextLength(article) {
  let length = 0;
  for (const block of article.body || []) {
    if (block.type === "p") length += String(block.text || "").length;
    if (block.type === "list") length += (block.items || []).reduce((sum, item) => sum + String(item).length, 0);
    if (block.type === "table") {
      length += (block.head || []).reduce((sum, cell) => sum + String(cell).length, 0);
      length += (block.rows || []).reduce((sum, row) => sum + row.reduce((s, cell) => s + String(cell).length, 0), 0);
    }
    if (block.type === "factbox") {
      length += String(block.title || "").length;
      length += (block.rows || []).reduce((sum, row) => sum + String(row.label || "").length + String(row.value || "").length, 0);
    }
  }
  return length;
}

export function countNewsH2(article) {
  return (article.body || []).filter((block) => block.type === "h2").length;
}

export function hasNewsFigureBlock(article) {
  return (article.body || []).some((block) => block.type === "table" || block.type === "factbox" || block.type === "figure");
}

// ブロック配列を HTML にする。figure の src は /assets/news/ 配下のみ許可する。
// options.h2IdPrefix を渡すと h2 に連番 id（目次アンカー用）を付ける。
export function renderNewsBlocks(blocks, options = {}) {
  const html = [];
  let h2Index = 0;
  for (const block of blocks || []) {
    if (block.type === "p") {
      html.push(`<p>${escapeNewsHtml(block.text)}</p>`);
    } else if (block.type === "h2") {
      h2Index += 1;
      const idAttr = options.h2IdPrefix ? ` id="${options.h2IdPrefix}${h2Index}"` : "";
      html.push(`<h2${idAttr}>${escapeNewsHtml(block.text)}</h2>`);
    } else if (block.type === "list") {
      html.push(`<ul>${(block.items || []).map((item) => `<li>${escapeNewsHtml(item)}</li>`).join("")}</ul>`);
    } else if (block.type === "table") {
      const head = (block.head || []).map((cell) => `<th scope="col">${escapeNewsHtml(cell)}</th>`).join("");
      const rows = (block.rows || []).map((row) => `<tr>${row.map((cell) => `<td>${escapeNewsHtml(cell)}</td>`).join("")}</tr>`).join("");
      html.push(`<figure class="news-table-wrap">${block.caption ? `<figcaption>${escapeNewsHtml(block.caption)}</figcaption>` : ""}<table class="news-table">${head ? `<thead><tr>${head}</tr></thead>` : ""}<tbody>${rows}</tbody></table></figure>`);
    } else if (block.type === "factbox") {
      const rows = (block.rows || []).map((row) => `<div class="news-factbox-row"><dt>${escapeNewsHtml(row.label)}</dt><dd>${escapeNewsHtml(row.value)}</dd></div>`).join("");
      html.push(`<aside class="news-factbox"><h3>${escapeNewsHtml(block.title)}</h3><dl>${rows}</dl></aside>`);
    } else if (block.type === "figure") {
      const src = String(block.src || "");
      if (!src.startsWith("/assets/news/")) continue;
      html.push(`<figure class="news-figure"><img src="${escapeNewsHtml(src)}" alt="${escapeNewsHtml(block.alt || "")}" loading="lazy" />${block.caption ? `<figcaption>${escapeNewsHtml(block.caption)}</figcaption>` : ""}</figure>`);
    }
  }
  return html.join("\n");
}

