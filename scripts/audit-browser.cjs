async (page) => {
  const assert = (condition,message) => { if(!condition) throw new Error(message); };
  const base = "http://127.0.0.1:8788";
  const results = [];
  const errors = [];
  page.on("pageerror",error=>errors.push(error.message));
  await page.addInitScript(()=>{
    if (window.auditInstrumentationInstalled) return;
    window.auditInstrumentationInstalled = true;
    window.auditLongTasks=[]; window.auditInputDelays=[];
    new PerformanceObserver(list=>window.auditLongTasks.push(...list.getEntries().map(item=>({start:item.startTime,duration:item.duration})))).observe({type:"longtask",buffered:true});
    document.addEventListener("input",event=>{
      if(event.target.id!=="searchInput")return;
      const start=performance.now();requestAnimationFrame(()=>window.auditInputDelays.push(performance.now()-start));
    });
  });
  await page.setViewportSize({width:390,height:844});
  await page.goto(base);
  await page.locator("#facilityList .facility-card").first().waitFor();
  await page.evaluate(()=>localStorage.removeItem("saincho-profile-v1"));
  await page.reload();
  await page.locator("#facilityList .facility-card").first().waitFor();
  await page.locator("#searchInput").fill("さうなもんきー");
  await page.waitForFunction(()=>document.querySelector("#facilityList h3")?.textContent==="SAUNA MONKEY");
  const coldTasks=await page.evaluate(()=>window.auditLongTasks);
  results.push({check:"cold-search",maxLongTaskMs:Math.max(0,...coldTasks.map(t=>t.duration))});
  for(const query of ["サウナモンキー","Sauna monkey","ｻｳﾅﾓﾝｷｰ","湯〜とぴあ宝","湯ーとピア宝","ゆーとぴあ宝"]){
    await page.locator("#searchInput").fill(query);
    await page.waitForTimeout(350);
    const names=await page.locator("#facilityList h3").allTextContents();
    assert(names.some(name=>query.includes("宝") ? /宝/.test(name) : /MONKEY/.test(name)),`Search failed: ${query}`);
    results.push({query,names});
  }
  await page.locator("#searchInput").fill("サウナ");
  await page.waitForTimeout(400);
  assert((await page.locator("#searchResultsStatus").textContent()).includes("全国"),"Broad query is trapped in one prefecture");
  assert(await page.locator("#facilityList .facility-card").count()<=36,"Unbounded list render");
  await page.locator("#searchInput").fill("");
  await page.locator("#searchInput").pressSequentially("sauna monkey",{delay:25});
  await page.waitForTimeout(400);
  const delays=await page.evaluate(()=>window.auditInputDelays.sort((a,b)=>a-b));
  results.push({check:"typing-next-frame",samples:delays.length,p95Ms:delays[Math.floor(delays.length*.95)]||0});
  await page.getByRole("button",{name:"サ印",exact:true}).click();
  assert(await page.locator(".stamp-tile").count()===36,"Passport renders too many tiles");
  await page.locator("[data-show-more-passport]").click();
  assert(await page.locator(".stamp-tile").count()===72,"Passport load more failed");
  await page.locator('[data-passport-prefecture="北海道"]').click();
  assert(await page.locator(".stamp-tile").count()===36,"Passport filter does not reset pagination");
  await page.locator(".stamp-tile").first().click();
  await page.locator(".facility-detail").waitFor();
  results.push({check:"passport-pagination-and-detail",passed:true});
  await page.getByRole("button",{name:"記録",exact:true}).click();
  await page.locator("#profileNickname").fill("監査用サウナー");
  await page.locator("#profileEmail").fill(`audit-${Date.now()}@example.test`);
  await page.route("**/api/ranking",route=>route.fulfill({status:503,contentType:"application/json",body:'{"error":"temporary"}'}));
  await page.locator("#profileForm button[type=submit]").click();
  await page.waitForFunction(()=>document.querySelector("#profileFeedback").textContent.includes("送信できません"));
  assert(await page.locator("#profileNickname").inputValue()==="監査用サウナー","Profile draft lost on failed save");
  await page.unroute("**/api/ranking");
  const retryRead = page.waitForResponse(response=>response.url().endsWith("/api/ranking") && response.request().method()==="GET");
  await page.locator("#leaderboardSyncButton").click();
  assert((await retryRead).status()===200,"Ranking reload failed after write error");
  assert((await page.locator("#profileFeedback").textContent()).includes("送信できません"),"Read success hides failed registration");
  const registration = page.waitForResponse(response=>response.url().endsWith("/api/ranking") && response.request().method()==="POST");
  await page.locator("#profileForm button[type=submit]").click();
  assert((await registration).status()===200,"Ranking registration was not accepted");
  await page.waitForFunction(()=>document.querySelector("#profileFeedback").textContent.includes("この端末に保存"));
  const refresh = page.waitForResponse(response=>response.url().endsWith("/api/ranking") && response.request().method()==="GET");
  await page.locator("#leaderboardSyncButton").click();
  assert((await refresh).status()===200,"Refresh button does not reload public ranking");
  results.push({check:"ranking-register-retry",passed:true});
  await page.screenshot({path:"output/playwright/audit-2026-10-18/03-after-ranking.png"});
  await page.goto(base+"/facility/st-aichi-4936/");
  await page.locator(".review-panel").waitFor();
  const input=page.locator("[data-review-input]");
  await input.fill("監査テスト用の口コミ。ローカル環境だけの投稿です。");
  await page.locator("[data-review-rating]").selectOption("4");
  await page.locator("[data-action=wishlist]").first().click();
  assert((await input.inputValue()).includes("監査テスト"),"Review draft lost on rerender");
  assert(await page.locator("[data-review-rating]").inputValue()==="4","Review rating draft lost");
  await page.route("**/api/reviews",route=>route.request().method()==="POST"?route.fulfill({status:503,body:'{}'}):route.continue());
  await page.getByRole("button",{name:"口コミを公開する",exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector("[data-action=save-review]").disabled);
  assert((await input.inputValue()).includes("監査テスト"),"Review lost on failed save");
  await page.unroute("**/api/reviews");
  await page.getByRole("button",{name:"口コミを公開する",exact:true}).click();
  await page.waitForFunction(()=>document.querySelector(".review-list")?.textContent.includes("監査テスト"));
  assert(await input.inputValue()==="","Review draft not cleared after confirmed publication");
  await page.screenshot({path:"output/playwright/audit-2026-10-18/04-after-review.png"});
  await page.route("**/api/reviews?**",route=>route.request().method()==="DELETE"?route.fulfill({status:403,body:'{}'}):route.continue());
  await page.locator("[data-action=delete-review]").first().click();
  await page.waitForTimeout(250);
  assert((await page.locator(".review-list").textContent()).includes("監査テスト"),"Failed delete removed public review from UI");
  await page.unroute("**/api/reviews?**");
  await page.locator("[data-action=delete-review]").first().click();
  await page.waitForFunction(()=>!document.querySelector(".review-list")?.textContent.includes("監査テスト"));
  results.push({check:"review-draft-retry-post-delete",passed:true});
  await page.goto(base+"/pref/tokyo/");
  await page.locator("#facilityList .facility-card").first().waitFor();
  assert((await page.locator('link[rel=canonical]').getAttribute("href")).endsWith("/pref/tokyo/"),"Pref canonical overwritten");
  await page.goto(base+"/guide/");
  const html=await(await page.request.get(base+"/guide/")).text();
  const articlePath=html.match(/href="(\/guide\/[^"/]+\/)"/)?.[1];
  assert(Boolean(articlePath),"No article link");
  await page.goto(base+articlePath);
  await page.waitForTimeout(500);
  assert(await page.locator("#ssrContent").isVisible(),"Article disappears after hydration");
  assert((await page.locator('link[rel=canonical]').getAttribute("href")).includes(articlePath),"Article canonical overwritten");
  await page.screenshot({path:"output/playwright/audit-2026-10-18/05-after-article.png"});
  await page.getByRole("button",{name:"探す",exact:true}).click();
  assert((await page.locator('link[rel=canonical]').getAttribute("href")).endsWith("pages.dev/"),"Article canonical survives navigation to home");
  await page.goBack();
  await page.locator("#ssrContent").waitFor({state:"visible"});
  assert((await page.locator('link[rel=canonical]').getAttribute("href")).includes(articlePath),"Article not restored by browser back");
  results.push({check:"pref-and-article-seo-after-hydration",passed:true});
  for(const width of [320,390,768,1440]){
    await page.setViewportSize({width,height:width>=768?1000:844});
    await page.goto(base);
    await page.locator("#facilityList .facility-card").first().waitFor();
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
    assert(!overflow,`Page overflows at ${width}`);
    const searchTop=await page.locator("#searchInput").evaluate(e=>e.getBoundingClientRect().top);
    await page.screenshot({path:`output/playwright/audit-2026-10-18/06-after-home-${width}.png`});
    results.push({check:"layout",width,overflow,searchTop});
  }
  assert(!errors.length,`Runtime errors: ${errors.join("; ")}`);
  return {ok:true,results,runtimeErrors:errors};
}
